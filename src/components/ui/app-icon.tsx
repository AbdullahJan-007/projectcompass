export interface AppIconProps {
  name: string;
  className?: string;
  strokeWidth?: number;
}

/**
 * Zero-network, inline SVG icon primitive backed by `lucide-react`.
 * Eliminates external icon-font failure modes where raw ligature text leaks into the UI.
 */
export function AppIcon({ name, className, strokeWidth = 1.85 }: AppIconProps) {
  const normalized = name.trim();
  const IconComponent = ICON_MAP[normalized] ?? Award;
  return (
    <IconComponent
      aria-hidden="true"
      strokeWidth={strokeWidth}
      className={cn("h-[1em] w-[1em] shrink-0 inline-block align-middle", className)}
    />
  );
}
